export type StickerDoodleName = keyof typeof STICKER_DOODLES;

export const STICKER_DOODLE_NAMES = Object.keys(STICKER_DOODLES) as StickerDoodleName[];

function hashStickerId(id: string, seed = 0): number {
  let hash = seed;
  for (const char of id) hash = (Math.imul(hash, 31) + char.charCodeAt(0)) | 0;
  return hash >>> 0;
}

/** 同一便签固定使用同一枚底图，不随列表顺序改变。 */
export function getStickerDoodleForId(id: string): StickerDoodleName {
  return STICKER_DOODLE_NAMES[hashStickerId(id) % STICKER_DOODLE_NAMES.length];
}

export type StickerScatterVariant = 0 | 1 | 2 | 3 | 4 | 5;

/** 便签的错落姿态由 ID 决定，排序或重新渲染不会改变它。 */
export function getStickerScatterVariant(id: string): StickerScatterVariant {
  return (hashStickerId(id, 17) % 6) as StickerScatterVariant;
}

/** 将共享线稿编码为编辑器 WebView 可用的本地 CSS 背景。 */
export function getStickerDoodleDataUri(
  name: StickerDoodleName,
  ink: string,
  opacity: number,
): string {
  const doodle = STICKER_DOODLES[name];
  const stroke = /^#[0-9a-fA-F]{6}$/.test(ink) ? ink : '#26352A';
  const alpha = Math.max(0, Math.min(1, opacity));
  const paths = doodle.paths.map((path) => `<path d="${path}"/>`).join('');
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${doodle.viewBox}" fill="none" stroke="${stroke}" stroke-opacity="${alpha}" stroke-width="3.8" stroke-linecap="round" stroke-linejoin="round">${paths}</svg>`;
  return `data:image/svg+xml,${encodeURIComponent(svg)}`;
}
